#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.txt from the licence files of the vendored code (REL-4).

Lists exactly the third-party code the plug-in binary holds: JUCE, pffft and what the JUCE modules
it links compile in (the audio codecs and WebP are switched off in src/CMakeLists.txt). Versions
come from external/JUCE/JUCE.spdx.json and the submodule commits; licence texts are copied
verbatim from external/.

    tools/third-party-notices.py            rewrite THIRD-PARTY-NOTICES.txt
    tools/third-party-notices.py --check    exit 1 if the file is out of date (local-check.sh)
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JUCE = ROOT / "external" / "JUCE"
OUTPUT = ROOT / "THIRD-PARTY-NOTICES.txt"
APACHE = "Apache License 2.0"
SOURCE_URL = "https://github.com/ffsfdfhbdg01/Sam-spectral-control"

# (SPDX package name, title, scope, licence file relative to external/, copyright line or None)
COMPONENTS = [
    ("zlib", "zlib", None, "JUCE/modules/juce_core/zip/zlib/LICENSE", None),
    ("HarfBuzz", "HarfBuzz", None, "JUCE/modules/juce_graphics/fonts/harfbuzz/COPYING", None),
    ("SheenBidi", "SheenBidi", None, APACHE, "Copyright (C) 2014-2025 Muhammad Tayyab Akram"),
    ("LunaSVG", "LunaSVG", None, "JUCE/modules/juce_graphics/drawables/lunasvg/LICENSE", None),
    ("PlutoVG", "PlutoVG", None, "JUCE/modules/juce_graphics/drawables/lunasvg/plutovg/LICENSE", None),
    ("libpng", "libpng", None, "JUCE/modules/juce_graphics/image_formats/pnglib/LICENSE", None),
    ("jpeglib", "The Independent JPEG Group's JPEG software", None, "IJG", None),
    ("VST3 SDK", "VST 3 SDK", None,
     "JUCE/modules/juce_audio_processors_headless/format_types/VST3_SDK/LICENSE.txt", None),
    ("pslextensions", "PreSonus Plug-In Extensions", None, "PUBLIC-DOMAIN", None),
    ("AudioUnitSDK", "AudioUnitSDK", "Audio Unit component on macOS only", APACHE,
     "Copyright (c) 2000-2021 Apple Inc."),
]
APACHE_FILE = "JUCE/modules/juce_graphics/unicode/sheenbidi/LICENSE"
IJG_README = "JUCE/modules/juce_graphics/image_formats/jpglib/README"
PSL_HEADER = "JUCE/modules/juce_audio_processors_headless/format_types/pslextensions/ipslcontextinfo.h"
RULE = "=" * 78


def read(relative):
    text = (ROOT / "external" / relative).read_text(encoding="utf-8")
    return "\n".join(line.rstrip() for line in text.strip("\n").splitlines())


def submodule_commit(path):
    return subprocess.run(["git", "-C", str(ROOT), "rev-parse", f"HEAD:{path}"], check=True,
                          capture_output=True, text=True).stdout.strip()


def ijg_legal_issues():
    # The IJG licence is the LEGAL ISSUES section of the README, up to the notes on build scripts.
    lines = read(IJG_README).splitlines()
    start = lines.index("LEGAL ISSUES")
    end = next(i for i in range(start, len(lines)) if lines[i].startswith("The Unix configuration script"))
    return "\n".join(lines[start:end]).rstrip()


def public_domain_notice():
    lines = [line.removeprefix("//").strip() for line in read(PSL_HEADER).splitlines()[:4]]
    return "\n".join(line for line in lines if "PreSonus" in line or "PUBLIC DOMAIN" in line)


def licence_name(package):
    declared = package["licenseDeclared"]
    return "public domain" if declared == "LicenseRef-Public-Domain" else declared


def generate():
    spdx = json.loads((JUCE / "JUCE.spdx.json").read_text(encoding="utf-8"))
    packages = {p["name"]: p for p in spdx["packages"]}
    juce = packages["JUCE"]
    pffft_commit = submodule_commit("external/pffft")
    juce_commit = submodule_commit("external/JUCE")

    out = [
        "Sam Spectral Control - third-party software notices",
        RULE,
        "",
        "Sam Spectral Control contains the third-party software listed below. Each component's",
        "licence follows in full. The Independent JPEG Group asks for this sentence: this software is",
        "based in part on the work of the Independent JPEG Group.",
        "",
        "VST is a registered trademark of Steinberg Media Technologies GmbH.",
        "",
        "Generated by tools/third-party-notices.py from the licence files in the source tree.",
        "",
        "Components",
        "----------",
        f"  JUCE {juce['versionInfo']} (commit {juce_commit[:12]}) - AGPL-3.0-only (used under the AGPLv3)",
        f"  pffft (commit {pffft_commit[:12]}) - FFTPACK licence (BSD-style)",
    ]
    for name, title, scope, _, _ in COMPONENTS:
        package = packages[name]
        version = "" if package["versionInfo"] == "NOASSERTION" else f" {package['versionInfo']}"
        extra = f"; {scope}" if scope else ""
        out.append(f"  {title}{version} - {licence_name(package)}{extra}")

    def section(title, body):
        out.extend(["", "", RULE, title, RULE, "", body])

    section(f"JUCE {juce['versionInfo']} - https://juce.com",
            "The JUCE framework modules are dual-licensed under the GNU Affero General Public License\n"
            "version 3 and the commercial JUCE licence. Sam Spectral Control uses JUCE under the GNU\n"
            "Affero General Public License version 3; the full text of that licence is in LICENSE.txt,\n"
            "which covers Sam Spectral Control as well. The complete corresponding source code, JUCE\n"
            "included, is available at\n"
            f"{SOURCE_URL}\n"
            "(one tag per version; every release also carries a source archive).\n"
            "JUCE's own licence summary follows.\n\n"
            + read("JUCE/LICENSE.md"))
    section("pffft - https://github.com/marton78/pffft", read("pffft/LICENSE.txt"))
    for name, title, scope, licence, copyright_line in COMPONENTS:
        package = packages[name]
        location = package["downloadLocation"]
        heading = title if location == "NOASSERTION" else f"{title} - {location}"
        if scope:
            heading += f"\n{scope}"
        if licence == APACHE:
            body = f"{copyright_line}\n\nLicensed under the Apache License, Version 2.0 (full text at the end)."
        elif licence == "IJG":
            body = ijg_legal_issues()
        elif licence == "PUBLIC-DOMAIN":
            body = public_domain_notice()
        else:
            body = read(licence)
        section(heading, body)
    section("Apache License, Version 2.0 (SheenBidi, AudioUnitSDK)", read(APACHE_FILE))
    return "\n".join(out) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.name} is out of date: run tools/third-party-notices.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
